-- ============================================================================

-- POC_USER_MAS : PoC 포털 사용자 계정
CREATE TABLE POC_USER_MAS (
  USER_ID       VARCHAR2(50)   NOT NULL,
  USER_NM       VARCHAR2(100)  NOT NULL,
  ORG_CD        VARCHAR2(10)   NOT NULL,
  DEPT_NM       VARCHAR2(100),
  ROLE_CD       VARCHAR2(20)   NOT NULL,
  PWD_HASH      VARCHAR2(256)  NOT NULL,
  PWD_SALT      VARCHAR2(64)   NOT NULL,
  USE_YN        CHAR(1)        DEFAULT 'Y' NOT NULL,
  LAST_LOGIN_DT VARCHAR2(30),
  REG_DT        VARCHAR2(30)   NOT NULL,
  UPD_DT        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_POC_USER_MAS PRIMARY KEY (USER_ID),
  CONSTRAINT CK_POC_USER_ROLE CHECK (ROLE_CD IN ('ADMIN','DEVELOPER','VIEWER')),
  CONSTRAINT CK_POC_USER_ORG CHECK (ORG_CD IN ('SKAX','SKHYNIX')),
  CONSTRAINT CK_POC_USER_USE CHECK (USE_YN IN ('Y','N'))
);
COMMENT ON TABLE POC_USER_MAS IS 'PoC 포털 사용자 계정';

-- POC_PRJ_MAS : PoC 과제 (목록용 컬럼 + 요구사항·단계 JSON)
CREATE TABLE POC_PRJ_MAS (
  PRJ_ID        VARCHAR2(20)   NOT NULL,
  PRJ_NM        VARCHAR2(200)  NOT NULL,
  SYS_NM        VARCHAR2(200),
  KIND_CD       VARCHAR2(10)   NOT NULL,
  DEPT_CD       VARCHAR2(50),
  PM_NM         VARCHAR2(100),
  DATA_JSON     CLOB           NOT NULL,
  REG_USER_ID   VARCHAR2(50),
  REG_DT        VARCHAR2(30)   NOT NULL,
  UPD_USER_ID   VARCHAR2(50),
  UPD_DT        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_POC_PRJ_MAS PRIMARY KEY (PRJ_ID)
);
COMMENT ON TABLE POC_PRJ_MAS IS 'PoC 과제 (목록용 컬럼 + 요구사항·단계 JSON)';

-- POC_CFG_MAS : PoC 포털 설정 (단가·업무 유형, JSON)
CREATE TABLE POC_CFG_MAS (
  CFG_KEY       VARCHAR2(100)  NOT NULL,
  CFG_JSON      CLOB           NOT NULL,
  VER_NO        NUMBER(6)      DEFAULT 1 NOT NULL,
  UPD_USER_ID   VARCHAR2(50),
  UPD_DT        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_POC_CFG_MAS PRIMARY KEY (CFG_KEY)
);
COMMENT ON TABLE POC_CFG_MAS IS 'PoC 포털 설정 (단가·업무 유형, JSON)';

-- POC_HIST_HIS : PoC 포털 변경 이력
CREATE TABLE POC_HIST_HIS (
  HIST_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
  TARGET_TYP    VARCHAR2(20)   NOT NULL,
  TARGET_ID     VARCHAR2(200)  NOT NULL,
  ACTION_CD     VARCHAR2(30)   NOT NULL,
  SUMMARY       VARCHAR2(500),
  DIFF_JSON     CLOB,
  USER_ID       VARCHAR2(50),
  USER_NM       VARCHAR2(100),
  REG_DT        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_POC_HIST_HIS PRIMARY KEY (HIST_ID)
);
CREATE INDEX IX_POC_HIST_TARGET ON POC_HIST_HIS (TARGET_TYP, TARGET_ID);
COMMENT ON TABLE POC_HIST_HIS IS 'PoC 포털 변경 이력';

-- POC_MEAS_DAT : 측정 데이터 (공수 입력·일 확정·AI 사용 세션, 종류별 JSON)
CREATE TABLE POC_MEAS_DAT (
  DAT_ID        VARCHAR2(200)  NOT NULL,
  KIND_CD       VARCHAR2(10)   NOT NULL,
  PRJ_ID        VARCHAR2(20)   NOT NULL,
  REQ_ID        VARCHAR2(50),
  WORK_DT       VARCHAR2(10),
  USER_ID       VARCHAR2(100),
  SRC_CD        VARCHAR2(20)   NOT NULL,
  DATA_JSON     CLOB           NOT NULL,
  REG_USER_ID   VARCHAR2(50),
  REG_DT        VARCHAR2(30)   NOT NULL,
  UPD_DT        VARCHAR2(30)   NOT NULL,
  CONSTRAINT PK_POC_MEAS_DAT PRIMARY KEY (DAT_ID),
  CONSTRAINT CK_POC_MEAS_KIND CHECK (KIND_CD IN ('EFFORT','CONF','AIUSE','NOTE'))
);
CREATE INDEX IX_POC_MEAS_KIND ON POC_MEAS_DAT (KIND_CD);
COMMENT ON TABLE POC_MEAS_DAT IS '측정 데이터 (공수 입력·일 확정·AI 사용 세션, 종류별 JSON)';

