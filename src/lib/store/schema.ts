export function renderSqlFile(): string {
  const head = [
    "-- ============================================================================",
    "-- PoC 포털 테이블 DDL",
    "--   앱이 Oracle 에 처음 연결될 때 없는 테이블을 자동으로 만든다(src/lib/store/schema.ts).",
    "--   DBA 가 수동으로 만들어야 하는 환경에서만 이 파일을 실행한다. 접속 계정이 소유자다.",
    "--   이 파일은 schema.ts 와 같아야 한다(tests/schema.test.ts 가 검사).",
    "-- ============================================================================",
    "",
  ];
  const body = TABLES.flatMap((t) => [`-- ${t.name} : ${t.comment}`, ...t.ddl.map((s) => `${s};`), ""]);
  const rollback = [
    "-- [ROLLBACK]",
    ...[...TABLES].reverse().map((t) => `-- DROP TABLE ${t.name} PURGE;`),
    "",
  ];
  return [...head, ...body, ...rollback].join("\n");
}
