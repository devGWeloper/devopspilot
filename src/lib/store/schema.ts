// 일시 컬럼을 VARCHAR2(ISO 8601) 로 두는 이유: 낙관적 동시성 비교(UPD_DT = :expected)를
// 앱의 문자열 그대로 하려면 TIMESTAMP 정밀도·세션 타임존 변환이 끼면 안 된다.

export interface TableDef {
  name: string;
  comment: string;
  ddl: string[];
}

function table(name: string, comment: string, body: string, extra: string[] = []): TableDef {
  return {
    name,
    comment,
    ddl: [`CREATE TABLE ${name} (\n${body}\n)`, ...extra, `COMMENT ON TABLE ${name} IS '${comment}'`],
  };
}

